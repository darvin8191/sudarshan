"""Writes ``frontend/src/sudarshan/watchlist/v2/types.ts`` from ``contract.py`` (M8.4, W3).

``python -m sudarshan.watchlists.gentypes`` writes the file; ``--check`` writes nothing and exits 1
when the file on disk differs from what the contract makes, which a test also asserts. The file is
never edited by hand. The output follows the frontend's formatter (single quotes, no semicolons,
2 spaces, 100 columns) so that nobody is tempted to run it through one and change it.
"""

from __future__ import annotations

import sys
from pathlib import Path

from sudarshan.watchlists import contract as c

TARGET = (
    Path(__file__).resolve().parents[2]
    / "frontend"
    / "src"
    / "sudarshan"
    / "watchlist"
    / "v2"
    / "types.ts"
)
HEADER = (
    "// Generated by sudarshan/watchlists/gentypes.py from sudarshan/watchlists/contract.py.\n"
    "// Do not edit by hand: change the contract and run the generator; a test fails on a\n"
    "// difference.\n"
)
_PRIM = {"string": "string", "int": "number", "number": "number", "bool": "boolean"}


def pascal(name: str) -> str:
    """``tv_preview`` to ``TvPreview``."""
    return "".join(p.capitalize() for p in name.split("_"))


def ts_type(typ: str) -> str:
    """A contract type as TypeScript."""
    t = typ.strip()
    nullable = t.endswith("|null")
    if nullable:
        t = t[:-5]
    array = t.endswith("[]")
    if array:
        t = t[:-2]
    out = _PRIM.get(t, t)
    if array:
        out += "[]"
    return out + (" | null" if nullable else "")


def _lit(value: object) -> str:
    if isinstance(value, str):
        return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"
    return str(value)


def _wrap_union(prefix: str, values: tuple[str, ...]) -> list[str]:
    one = prefix + " | ".join(_lit(v) for v in values)
    if len(one) <= 100:
        return [one]
    return [prefix.rstrip()] + [f"  | {_lit(v)}" for v in values]


def _interface(name: str, fields: tuple[c.Field, ...]) -> list[str]:
    if not fields:
        return [f"export type {name} = Record<string, never>"]
    lines = [f"export interface {name} {{"]
    for f in fields:
        lines.append(f"  {f.name}{'?' if f.optional else ''}: {ts_type(f.type)}")
    lines.append("}")
    return lines


def _const(name: str, value: object, ann: str = "") -> list[str]:
    return [f"export const {name}{ann} = {value}"]


def render() -> str:
    """The whole file, as text."""
    out = [HEADER]
    out += _const("API_PREFIX", _lit(c.API_PREFIX))
    out += _const("INTERNAL_PREFIX", _lit(c.INTERNAL_PREFIX))
    out += _const("ROOM", _lit(c.ROOM))
    out += _const("EVENT_PUSH", _lit(c.EVENT_PUSH))
    out += _const("EVENT_JOIN", _lit(c.EVENT_JOIN))
    out += ["", "export const LIMITS = {"]
    out += [f"  {k}: {v}," for k, v in c.LIMITS.items()] + ["} as const", ""]
    out += ["export const LIMITS_PER_MIN = {"]
    out += [f"  {k}: {v}," for k, v in c.LIMITS_PER_MIN.items()] + ["} as const", ""]
    out += ["export const ERROR_CODES = ["] + [f"  {_lit(k)}," for k in c.ERROR_CODES]
    out += ["] as const", "export type ErrorCode = (typeof ERROR_CODES)[number]", ""]
    for name, values in c.ENUMS.items():
        out += _wrap_union(f"export type {name} = ", values)
    out.append("")
    for name in c.RECORDS:
        out += _interface(name, c.record(name)) + [""]
    out += [
        "export interface ErrorEnvelope {",
        "  status: 'error'",
        "  code: ErrorCode",
        "  message: string",
        "  field?: string",
        "}",
        "export interface OkEnvelope<T> {",
        "  status: 'ok'",
        "  data: T",
        "}",
        "export type Envelope<T> = OkEnvelope<T> | ErrorEnvelope",
        "",
    ]
    out += ["export interface OpSpec {", "  name: OpName", "  method: string", "  route: string"]
    out += ["  cls: Cls", "}", ""]
    out += ["export const OPS: readonly OpSpec[] = ["]
    for op in c.OPS:
        out.append(
            f"  {{ name: {_lit(op.name)}, method: {_lit(op.method)}, "
            f"route: {_lit(op.route)}, cls: {_lit(op.cls)} }},"
        )
    out += ["]", ""]
    names = [_lit(n) for n in c.OP_NAMES]
    out += ["export type OpName ="] + [f"  | {n}" for n in names] + [""]
    for op in (*c.OPS, *c.INTERNAL_OPS):
        out += _interface(pascal(op.name) + "Req", c.parse_fields(op.req)) + [""]
    out += ["export interface WatchlistOps {"]
    for op in c.OPS:
        out.append(f"  {op.name}: {{ req: {pascal(op.name)}Req; res: {op.res} }}")
    out += ["}", "", "export interface InternalOps {"]
    for op in c.INTERNAL_OPS:
        out.append(f"  {op.name}: {{ req: {pascal(op.name)}Req; res: {op.res} }}")
    out += ["}", ""]
    return "\n".join(out)


def check(path: Path = TARGET) -> bool:
    """True when the file on disk is what the contract makes."""
    try:
        return path.read_text(encoding="utf-8") == render()
    except OSError:
        return False


def main(argv: list[str]) -> int:
    """Write the file, or with ``--check`` only compare."""
    if "--check" in argv:
        if check():
            return 0
        sys.stderr.write("v2/types.ts differs from contract.py: run gentypes without --check.\n")
        return 1
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
