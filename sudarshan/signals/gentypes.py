"""Writes ``frontend/src/sudarshan/signals/types.ts`` from ``contract.py`` (T0).

``python -m sudarshan.signals.gentypes`` writes the file; ``--check`` writes nothing and exits 1
when the file on disk differs from what the contract makes, which a test also asserts. The file is
never edited by hand: it changes with the contract. The output follows the frontend's formatter
(single quotes, no semicolons, 2 spaces, 100 columns) so that nobody is tempted to run it through
one and change it.
"""

from __future__ import annotations

import sys
from pathlib import Path

from sudarshan.signals import contract as c

TARGET = (
    Path(__file__).resolve().parents[2] / "frontend" / "src" / "sudarshan" / "signals" / "types.ts"
)
HEADER = (
    "// Generated by sudarshan/signals/gentypes.py from sudarshan/signals/contract.py.\n"
    "// Do not edit by hand: change the contract and run the generator; a test fails on a\n"
    "// difference.\n"
)
WIDTH = 100
_PRIM = {"string": "string", "int": "number", "number": "number", "bool": "boolean"}


def pascal(name: str) -> str:
    """``change_get`` to ``ChangeGet``."""
    return "".join(p.capitalize() for p in name.split("_"))


def ts_type(typ: str) -> str:
    """A contract type as TypeScript."""
    t = typ.strip()
    nullable = t.endswith("|null")
    if nullable:
        t = t[:-5]
    array = t.endswith("[]")
    if array:
        t = t[:-2]
    out = _PRIM.get(t, t)
    if array:
        out += "[]"
    return out + (" | null" if nullable else "")


def _lit(value: object) -> str:
    if isinstance(value, str):
        # The formatter's choice: single quotes, unless the text holds more of them than of
        # double quotes ("TRINETRA's clock" is written in double quotes, with no escape).
        quote = '"' if value.count("'") > value.count('"') else "'"
        return quote + value.replace("\\", "\\\\").replace(quote, "\\" + quote) + quote
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, tuple | list):
        return "[" + ", ".join(_lit(v) for v in value) + "]"
    return str(value)


def _key(name: str) -> str:
    return name if name.isidentifier() else _lit(name)


def _union(name: str, values: tuple[str, ...]) -> list[str]:
    prefix = f"export type {name} = "
    one = prefix + " | ".join(_lit(v) for v in values)
    if len(one) <= WIDTH:
        return [one]
    return [prefix.rstrip()] + [f"  | {_lit(v)}" for v in values]


def _tuple_const(name: str, values: tuple[str, ...]) -> list[str]:
    one = f"export const {name} = [" + ", ".join(_lit(v) for v in values) + "] as const"
    if len(one) <= WIDTH:
        return [one]
    return [f"export const {name} = ["] + [f"  {_lit(v)}," for v in values] + ["] as const"]


def _entry(key: str, value: object) -> list[str]:
    """One property of an object literal, broken after the colon when it does not fit, as the
    formatter does it: never after a key shorter than five characters (its indent plus three)."""
    one = f"  {_key(key)}: {_lit(value)},"
    if len(one) <= WIDTH or len(_key(key)) < 5:
        return [one]
    return [f"  {_key(key)}:", f"    {_lit(value)},"]


def _map_const(name: str, mapping: dict[str, object]) -> list[str]:
    out = [f"export const {name} = {{"]
    for key, value in mapping.items():
        out += _entry(key, value)
    return out + ["} as const"]


def _interface(name: str, fields: tuple[c.Field, ...]) -> list[str]:
    if not fields:
        return [f"export type {name} = Record<string, never>"]
    lines = [f"export interface {name} {{"]
    for f in fields:
        lines.append(f"  {f.name}{'?' if f.optional else ''}: {ts_type(f.type)}")
    lines.append("}")
    return lines


def render() -> str:
    """The whole file, as text."""
    out = [HEADER]
    for name, value in (
        ("SERVICE", c.SERVICE),
        ("CONTRACT_VERSION", c.VERSION),
        ("PORT", c.PORT),
        ("PAGE", c.PAGE),
        ("API_PREFIX", c.API_PREFIX),
        ("ROOM", c.ROOM),
        ("JOIN_EVENT", c.JOIN_EVENT),
        ("EVENT_UPDATE", c.EVENT_UPDATE),
        ("DEFAULT_LANG", c.DEFAULT_LANG),
        ("OTHER_MODULE_NAME", c.OTHER_MODULE_NAME),
        ("FRESH_GRACE_MS", c.FRESH_GRACE_MS),
        ("COLOUR_FOR_MS", c.COLOUR_FOR_MS),
        ("IST_OFFSET_S", c.IST_OFFSET_S),
    ):
        out.append(f"export const {name} = {_lit(value)}")
    out.append("")
    out += _map_const("TIMELINE", c.TIMELINE) + [""]
    out += _map_const("LIMITS_PER_MIN", c.LIMITS_PER_MIN) + [""]
    out += _map_const("ERROR_STATUS", c.ERROR_STATUS) + [""]
    out += _map_const("MODULE_NAMES", c.MODULE_NAMES) + [""]
    out += _map_const("LANG_NAMES", c.LANG_NAMES) + [""]
    out += _map_const("BIAS_WORDS", c.BIAS_WORDS) + [""]
    out += _map_const("HORIZON_WORDS", c.HORIZON_WORDS) + [""]
    out += _map_const("LEVEL_WORDS", c.LEVEL_WORDS) + [""]
    out += _map_const("CHANGE_WORDS", c.CHANGE_WORDS) + [""]
    out += _map_const("AGE_WORDS", c.AGE_WORDS) + [""]
    out += _map_const("WORDS", c.WORDS) + [""]
    out += _tuple_const("KNOWN_MODULES", c.KNOWN_MODULES)
    out += _tuple_const("INSTRUMENTS", c.INSTRUMENTS)
    out += _tuple_const("LANG_FALLBACK", c.LANG_FALLBACK)
    out += _tuple_const("MONTHS", c.MONTHS)
    out += _tuple_const("RELAYED_LEVELS", c.RELAYED_LEVELS)
    out += _tuple_const("OP_NAMES", tuple(op.name for op in c.OPS)) + [""]
    for name, values in c.ENUMS.items():
        out += _union(name, values)
    out += ["export type OpName = (typeof OP_NAMES)[number]", ""]
    for name in c.RECORDS:
        out += _interface(name, c.record(name)) + [""]
    out += ["export interface OpSpec {", "  name: OpName", "  method: string", "  route: string"]
    out += ["  cls: Cls", "}", "", "export const OPS: readonly OpSpec[] = ["]
    for op in c.OPS:
        out.append(
            f"  {{ name: {_lit(op.name)}, method: {_lit(op.method)}, "
            f"route: {_lit(op.route)}, cls: {_lit(op.cls)} }},"
        )
    out += ["]", ""]
    for op in c.OPS:
        out += _interface(pascal(op.name) + "Req", c.parse_fields(op.req)) + [""]
    out += ["export interface SignalsOps {"]
    for op in c.OPS:
        out.append(f"  {op.name}: {{ req: {pascal(op.name)}Req; res: {ts_type(op.res)} }}")
    out += ["}", ""]
    out += [
        "/** The bridge's envelope: a success, the view switched off, or an error. */",
        "export type Envelope<T> =",
        "  | { status: 'success'; enabled: true; data: T }",
        "  | { status: 'success'; enabled: false; data: null; message: string }",
        "  | { status: 'error'; error: { code: ErrorCode; message: string; field?: string } }",
        "",
    ]
    return "\n".join(out)


def check(path: Path = TARGET) -> bool:
    """True when the file on disk is what the contract makes."""
    try:
        return path.read_text(encoding="utf-8") == render()
    except OSError:
        return False


def main(argv: list[str]) -> int:
    """Write the file, or with ``--check`` only compare."""
    if "--check" in argv:
        if check():
            return 0
        sys.stderr.write(
            "signals/types.ts differs from contract.py: run gentypes without --check.\n"
        )
        return 1
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
