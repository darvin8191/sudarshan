"""Writes ``frontend/src/sudarshan/journal/types.ts`` from ``core/kinds.py`` (JF0).

``python -m sudarshan.journal.gentypes`` writes the file; ``--check`` writes nothing and exits 1
when the file on disk differs from what the contract makes, which a test also asserts. The file is
never edited by hand. The output follows the frontend's formatter (single quotes, no semicolons,
2 spaces, 100 columns) so that nobody is tempted to run it through one and change it.
"""

from __future__ import annotations

import sys
from pathlib import Path

from sudarshan.journal.core import kinds as k

TARGET = (
    Path(__file__).resolve().parents[2] / "frontend" / "src" / "sudarshan" / "journal" / "types.ts"
)
HEADER = (
    "// Generated by sudarshan/journal/gentypes.py from sudarshan/journal/core/kinds.py.\n"
    "// Do not edit by hand: change the contract and run the generator; a test fails on a\n"
    "// difference.\n"
)
_PRIM = {"string": "string", "int": "number", "number": "number", "bool": "boolean"}


def pascal(name: str) -> str:
    """``trip_get`` to ``TripGet``."""
    return "".join(p.capitalize() for p in name.split("_"))


def ts_type(typ: str) -> str:
    """A contract type as TypeScript."""
    t = typ.strip()
    nullable = t.endswith("|null")
    if nullable:
        t = t[:-5]
    array = t.endswith("[]")
    if array:
        t = t[:-2]
    out = _PRIM.get(t, t)
    if array:
        out += "[]"
    return out + (" | null" if nullable else "")


def _lit(value: object) -> str:
    if isinstance(value, str):
        return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"
    return str(value)


def _union(name: str, values: tuple[str, ...]) -> list[str]:
    prefix = f"export type {name} = "
    one = prefix + " | ".join(_lit(v) for v in values)
    if len(one) <= 100:
        return [one]
    return [prefix.rstrip()] + [f"  | {_lit(v)}" for v in values]


def _interface(name: str, fields: tuple[k.Field, ...]) -> list[str]:
    if not fields:
        return [f"export type {name} = Record<string, never>"]
    lines = [f"export interface {name} {{"]
    for f in fields:
        lines.append(f"  {f.name}{'?' if f.optional else ''}: {ts_type(f.type)}")
    lines.append("}")
    return lines


def _tuple_const(name: str, values: tuple[str, ...]) -> list[str]:
    one = f"export const {name} = [" + ", ".join(_lit(v) for v in values) + "] as const"
    if len(one) <= 100:
        return [one]
    return [f"export const {name} = ["] + [f"  {_lit(v)}," for v in values] + ["] as const"]


def _key(name: str) -> str:
    return name if name.isidentifier() else _lit(name)


def _map_const(name: str, mapping: dict[str, object]) -> list[str]:
    out = [f"export const {name} = {{"]
    out += [f"  {_key(key)}: {_lit(val)}," for key, val in mapping.items()]
    return out + ["} as const"]


def render() -> str:
    """The whole file, as text."""
    out = [HEADER]
    out += [f"export const SERVICE = {_lit(k.SERVICE)}", f"export const PORT = {k.PORT}"]
    out += [f"export const API_PREFIX = {_lit(k.API_PREFIX)}"]
    out += [f"export const PRICE_SCALE = {k.PRICE_SCALE}"]
    out += [f"export const PAISE_PER_RUPEE = {k.PAISE_PER_RUPEE}"]
    out += [f"export const IST_OFFSET_S = {k.IST_OFFSET_S}", ""]
    out += _map_const("LIMITS", k.LIMITS) + [""]
    out += _map_const("LIMITS_PER_MIN", k.LIMITS_PER_MIN) + [""]
    out += _map_const("RATIO_PLACES", k.RATIO_PLACES) + [""]
    out += _map_const("REPORT_TITLES", k.REPORT_TITLES) + [""]
    out += _map_const("HOLD_BUCKET_LABELS", k.HOLD_BUCKET_LABELS) + [""]
    out += _tuple_const("INTRADAY_PRODUCTS", k.INTRADAY_PRODUCTS)
    out += _tuple_const("CARRY_PRODUCTS", k.CARRY_PRODUCTS)
    out += _tuple_const("HOLD_BUCKETS", k.HOLD_BUCKETS)
    out += _tuple_const("DESK_STATES", k.DESK_STATES)
    out += _tuple_const("OP_NAMES", k.OP_NAMES) + [""]
    for name, values in k.ENUMS.items():
        out += _union(name, values)
    out.append("")
    for name in k.RECORDS:
        out += _interface(name, k.record(name)) + [""]
    out += ["export interface OpSpec {", "  name: OpName", "  method: string", "  route: string"]
    out += ["  cls: Cls", "}", "", "export const OPS: readonly OpSpec[] = ["]
    for op in k.OPS:
        out.append(
            f"  {{ name: {_lit(op.name)}, method: {_lit(op.method)}, "
            f"route: {_lit(op.route)}, cls: {_lit(op.cls)} }},"
        )
    out += ["]", "", "export type OpName = (typeof OP_NAMES)[number]", ""]
    for op in (*k.OPS, *k.SERVICE_OPS):
        out += _interface(pascal(op.name) + "Req", k.parse_fields(op.req)) + [""]
    out += ["export interface JournalOps {"]
    for op in (*k.OPS, *k.SERVICE_OPS):
        out.append(f"  {op.name}: {{ req: {pascal(op.name)}Req; res: {ts_type(op.res)} }}")
    out += ["}", ""]
    return "\n".join(out)


def check(path: Path = TARGET) -> bool:
    """True when the file on disk is what the contract makes."""
    try:
        return path.read_text(encoding="utf-8") == render()
    except OSError:
        return False


def main(argv: list[str]) -> int:
    """Write the file, or with ``--check`` only compare."""
    if "--check" in argv:
        if check():
            return 0
        sys.stderr.write("journal/types.ts differs from kinds.py: run gentypes without --check.\n")
        return 1
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
