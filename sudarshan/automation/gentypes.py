"""Writes ``frontend/src/sudarshan/automation/types.ts`` from ``contract.py`` (A1).

``python -m sudarshan.automation.gentypes`` prints the file; ``--write`` writes it; ``--check``
writes nothing and exits 1 when the file on disk differs. The page's lane owns the file and never
edits it by hand: it changes with the contract. The output follows the frontend's formatter
(single quotes, no semicolons, 2 spaces).
"""

from __future__ import annotations

import sys
from pathlib import Path

from . import contract as c
from . import flag
from . import model as m

TARGET = (
    Path(__file__).resolve().parents[2]
    / "frontend"
    / "src"
    / "sudarshan"
    / "automation"
    / "types.ts"
)
HEADER = (
    "// Generated by sudarshan/automation/gentypes.py from sudarshan/automation/contract.py.\n"
    "// Do not edit by hand: change the contract and run the generator.\n"
)


def _union(name: str, values) -> str:
    return f"export type {name} = " + " | ".join(f"'{value}'" for value in values)


def _interface(name: str, fields: dict[str, str]) -> list[str]:
    lines = [f"export interface {name} {{"]
    lines += [f"  {key}: {kind}" for key, kind in fields.items()]
    return [*lines, "}"]


def render() -> str:
    out = [HEADER.rstrip("\n"), ""]
    out.append(f"export const AUTOMATION_CONTRACT = {c.VERSION}")
    out.append(f"export const AUTOMATION_API = '{c.API_PREFIX}'")
    out.append(f"export const AUTOMATION_LINK = '{c.PUBLIC_PREFIX}'")
    out.append(f"export const AUTOMATION_PAGE = '{c.PAGE}'")
    out.append(f"export const AUTOMATION_EVENT = '{c.EVENT}'")
    out.append(f"export const AUTOMATION_ALERTS_PAGE = {c.ALERTS_PAGE}")
    out.append("")
    for name, values in (
        ("Stage", flag.STAGES),
        ("StrategyState", m.STATES),
        ("Mode", m.MODES),
        ("Kind", m.KINDS),
        ("Direction", m.DIRECTIONS),
        ("SizeMode", m.SIZE_MODES),
        ("Product", m.PRODUCTS),
        ("Verdict", m.VERDICTS),
    ):
        out.append(_union(name, values))
    out.append("")
    blocks = {
        "StrategyForm": c.FORM,
        "Strategy": c.STRATEGY,
        "AlertLine": c.ALERT,
        "SandboxRun": c.SANDBOX_RUN,
        "AlertMessages": c.ALERT_MESSAGES,
        "OtherAutomation": c.OTHER,
        "AutomationEvent": c.EVENT_FIELDS,
        **c.REQUESTS,
        **c.ANSWERS,
    }
    for name, fields in blocks.items():
        out += [*_interface(name, fields), ""]
    out.append("export const AUTOMATION_ROUTES = {")
    for method, path, _takes, answers, _kind in c.ROUTES:
        key = path.strip("/")
        out.append(f"  {key}: {{ method: '{method}', path: '{c.API_PREFIX}{path}' }}, // {answers}")
    out.append("} as const")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        same = TARGET.exists() and TARGET.read_text() == text
        if not same:
            sys.stderr.write(f"{TARGET.name} differs from the contract; run the generator\n")
        return 0 if same else 1
    if "--write" in argv:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(text)
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
