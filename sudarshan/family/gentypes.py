"""Writes ``frontend/src/sudarshan/family/types.ts`` from ``contract.py`` (P6 F0).

``python -m sudarshan.family.gentypes`` writes the file; ``--check`` writes nothing and exits 1
when the file on disk differs from what the contract makes, which a test also asserts. The file is
never edited by hand. The output follows the frontend's formatter (single quotes, no semicolons,
2 spaces, 100 columns) so that nobody is tempted to run it through one and change it.
"""

from __future__ import annotations

import sys
from pathlib import Path

from sudarshan.family import contract as c

TARGET = (
    Path(__file__).resolve().parents[2] / "frontend" / "src" / "sudarshan" / "family" / "types.ts"
)
HEADER = (
    "// Generated by sudarshan/family/gentypes.py from sudarshan/family/contract.py.\n"
    "// Do not edit by hand: change the contract and run the generator; a test fails on a\n"
    "// difference.\n"
)
_PRIM = {"string": "string", "int": "number", "number": "number", "bool": "boolean"}
_PRIM["json"] = "unknown"


def pascal(name: str) -> str:
    """``member_create`` to ``MemberCreate``."""
    return "".join(p.capitalize() for p in name.split("_"))


def ts_type(typ: str) -> str:
    """A contract type as TypeScript."""
    t = typ.strip()
    nullable = t.endswith("|null")
    if nullable:
        t = t[:-5]
    array = t.endswith("[]")
    if array:
        t = t[:-2]
    out = _PRIM.get(t, t)
    if array:
        out += "[]"
    return out + (" | null" if nullable else "")


def _lit(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"
    return str(value)


def _union(name: str, values: tuple[str, ...]) -> list[str]:
    prefix = f"export type {name} = "
    one = prefix + " | ".join(_lit(v) for v in values)
    if len(one) <= 100:
        return [one]
    return [prefix.rstrip()] + [f"  | {_lit(v)}" for v in values]


def _key(name: str) -> str:
    return name if name.isidentifier() else _lit(name)


def _interface(name: str, fields: tuple[c.Field, ...]) -> list[str]:
    if not fields:
        return [f"export type {name} = Record<string, never>"]
    lines = [f"export interface {name} {{"]
    for f in fields:
        lines.append(f"  {_key(f.name)}{'?' if f.optional else ''}: {ts_type(f.type)}")
    lines.append("}")
    return lines


def _const(name: str, value: object) -> list[str]:
    return [f"export const {name} = {_lit(value)}"]


def _map(name: str, mapping: dict[str, object]) -> list[str]:
    out = [f"export const {name} = {{"]
    out += [f"  {_key(key)}: {_lit(val)}," for key, val in mapping.items()]
    return out + ["} as const"]


def _tuple(name: str, values: tuple[str, ...]) -> list[str]:
    one = f"export const {name} = [" + ", ".join(_lit(v) for v in values) + "] as const"
    if len(one) <= 100:
        return [one]
    return [f"export const {name} = ["] + [f"  {_lit(v)}," for v in values] + ["] as const"]


def render() -> str:
    """The whole file, as text."""
    out = [HEADER]
    for name in ("SERVICE", "PORT", "VIEWER_PREFIX", "WS_PATH", "COOKIE", "CSRF_COOKIE"):
        out += _const(name, getattr(c, name))
    out += _const("CSRF_HEADER", c.CSRF_HEADER)
    out += _const("WS_CLOSE_SIGNED_OUT", c.WS_CLOSE_SIGNED_OUT) + [""]
    out += _map("LIMITS", c.LIMITS) + [""]
    out += _map("ERROR_STATUS", c.ERROR_STATUS) + [""]
    out += _tuple("CATEGORIES", c.CATEGORIES)
    out += ["export const PRIVACY_DEFAULTS = {"]
    for role, shown in c.PRIVACY_DEFAULTS.items():
        values = ", ".join(f"{k}: {_lit(v)}" for k, v in shown.items())
        out.append(f"  {role}: {{ {values} }},")
    out += ["} as const", ""]
    for name, values in c.ENUMS.items():
        out += _union(name, values)
    out += ["export type ErrorCode = keyof typeof ERROR_STATUS", ""]
    for name in c.RECORDS:
        out += _interface(name, c.record(name)) + [""]
    out += [
        "export interface ErrorEnvelope {",
        "  status: 'error'",
        "  code: ErrorCode",
        "  message: string",
        "  field?: string",
        "}",
        "export interface OkEnvelope<T> {",
        "  status: 'success'",
        "  data: T",
        "}",
        "export type Envelope<T> = OkEnvelope<T> | ErrorEnvelope",
        "",
        "export interface ViewerOpSpec {",
        "  name: ViewerOpName",
        "  method: string",
        "  route: string",
        "  auth: Auth",
        "}",
        "",
        "export const VIEWER_OPS: readonly ViewerOpSpec[] = [",
    ]
    for op in c.VIEWER_OPS:
        parts = [("name", op.name), ("method", op.method), ("route", op.route), ("auth", op.auth)]
        one = "  { " + ", ".join(f"{k}: {_lit(v)}" for k, v in parts) + " },"
        if len(one) <= 100:
            out.append(one)
        else:  # as the formatter breaks an object that does not fit
            out += ["  {"] + [f"    {k}: {_lit(v)}," for k, v in parts] + ["  },"]
    out += ["]", ""]
    out += _union("ViewerOpName", c.VIEWER_OP_NAMES)
    out += _union("AdminOpName", c.ADMIN_OP_NAMES) + [""]
    for op in c.VIEWER_OPS:
        out += _interface(pascal(op.name) + "Req", c.parse_fields(op.req)) + [""]
    for op in (*c.ADMIN_OPS, *c.NUDGE_OPS):
        out += _interface("Admin" + pascal(op.name) + "Req", c.parse_fields(op.req)) + [""]
    for op in c.INTERNAL_OPS:
        out += _interface("Internal" + pascal(op.name) + "Req", c.parse_fields(op.req)) + [""]
    out += ["export interface ViewerOps {"]
    for op in c.VIEWER_OPS:
        out.append(f"  {op.name}: {{ req: {pascal(op.name)}Req; res: {ts_type(op.res)} }}")
    out += ["}", "", "// An admin op switched off answers Off in place of its own answer."]
    out += ["export interface AdminOps {"]
    for op in c.ADMIN_OPS:
        out.append(f"  {op.name}: {{ req: Admin{pascal(op.name)}Req; res: {ts_type(op.res)} }}")
    out += ["}", ""]
    return "\n".join(out)


def check(path: Path = TARGET) -> bool:
    """True when the file on disk is what the contract makes."""
    try:
        return path.read_text(encoding="utf-8") == render()
    except OSError:
        return False


def main(argv: list[str]) -> int:
    """Write the file, or with ``--check`` only compare."""
    if "--check" in argv:
        if check():
            return 0
        sys.stderr.write(
            "family/types.ts differs from contract.py: run gentypes without --check.\n"
        )
        return 1
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
